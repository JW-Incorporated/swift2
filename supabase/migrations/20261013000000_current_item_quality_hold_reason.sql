-- Content fix 3/6: hard publish gate. `writeCurrentItem` now runs every
-- extracted `current_item` through `@swift2/shared`'s
-- `evaluateCurrentItemQuality` (image present + allowlisted, summary/detail
-- length floors, redline ok) before deciding whether the row is servable.
-- `quality_hold_reason` records WHY a row is held (distinct from
-- `redline_ok`, which only reflects the topic-redline screen) so the next
-- worker cycle's re-enrichment pass (Cards 1-2) and human triage both know
-- exactly what to fix, without re-deriving it from the row's own fields.
--
-- Servability itself still rides on the existing `redline_ok` column and
-- its RLS policy (`current_item public read`, 20260901000000_knowledge_
-- engine.sql) — `writeCurrentItem` sets `redline_ok` to the AND of the
-- redline screen AND this quality gate, so an unvetted migration of the
-- RLS policy is not required for the gate to take effect: a quality
-- failure already makes `redline_ok = false`, which the existing anon-read
-- policy already excludes. This column is purely diagnostic/retry-driving,
-- never read by RLS.
alter table public.current_item add column if not exists quality_hold_reason text;
