// Shared helpers for the concert-photo-sourcing adapters (press + Openverse;
// the Wikimedia and Reddit adapters predate this file and keep their own).
// Candidates are the exact shape `import-photo-library.mjs --fetch` expects.

export const MIN_PRESS_LONG_EDGE_PX = 1080;
export const TOPIC_RE = /taylor swift/i;

// The owner's hard bar (docs/social/guardrails.md Guardrail 2): no AI-generated
// images of Taylor, ever. Openverse indexes Flickr "AI art" uploads, so any
// AI marker in the title/tags/description drops the photo.
const AI_MARKER_RE = /\b(ai[- ]?generated|ai[- ]?art|aiart|a\.i\.|midjourney|stable ?diffusion|dall[- ]?e|deepfake|generated by ai|made with ai)\b|(^|[\s,;#"'])ai([\s,;#"']|$)/i;

/** True when the text carries an AI-generation marker. */
export function looksAiGenerated(...parts) {
  return AI_MARKER_RE.test(parts.filter((p) => typeof p === 'string').join(' '));
}

/** Lowercased host + path with query/hash/trailing slash dropped — the key used to match the same asset across sources. */
export function normalizeSourceUrl(value) {
  try {
    const url = new URL(value);
    const host = url.hostname.toLowerCase().replace(/^www\./, '');
    let pathname = url.pathname;
    try {
      pathname = decodeURIComponent(pathname);
    } catch {
      // keep the raw path
    }
    return `${host}${pathname.replace(/\/+$/, '')}`;
  } catch {
    return null;
  }
}

// A candidate's identity: its id and its image URL. Its `source` page is NOT
// part of in-run identity (one press article legitimately yields two image
// candidates), only of the cross-source `excludeKeys` check below.
function dedupeKeys(candidate) {
  return [
    `id:${candidate.id}`,
    candidate.sourceUrl ? `url:${normalizeSourceUrl(candidate.sourceUrl)}` : null,
  ].filter(Boolean);
}

function pageKey(candidate) {
  return candidate.source ? `url:${normalizeSourceUrl(candidate.source)}` : null;
}

/**
 * Drops candidates repeating an earlier id or image URL (first occurrence wins,
 * stable order), and any whose id, image URL or `source` page is in `excludeKeys`
 * (see `candidateKeys` — e.g. Openverse mirrors of Wikimedia files).
 */
export function dedupeCandidates(candidates, { excludeKeys = new Set() } = {}) {
  const seen = new Set();
  const out = [];
  for (const candidate of candidates) {
    const keys = dedupeKeys(candidate);
    if (keys.some((key) => seen.has(key) || excludeKeys.has(key))) continue;
    const page = pageKey(candidate);
    if (page && excludeKeys.has(page)) continue;
    for (const key of keys) seen.add(key);
    out.push(candidate);
  }
  return out;
}

/** Dedupe keys (id, image URL, source page) of an already-sourced list, for `excludeKeys`. */
export function candidateKeys(candidates) {
  return new Set(candidates.flatMap((candidate) => [...dedupeKeys(candidate), pageKey(candidate)].filter(Boolean)));
}

/**
 * Round-robin merge of per-source candidate lists, skipping known ids and
 * duplicates (earlier sources win), capped at `max`. Round-robin, not
 * concatenation, so a source with thousands of candidates (Wikimedia) cannot
 * starve the others out of the per-run cap.
 */
export function mergeCandidates(sources, { known = new Set(), max = 300 } = {}) {
  const seen = new Set();
  const queues = sources.map((list) =>
    list.filter((candidate) => {
      if (known.has(candidate.id)) return false;
      const keys = dedupeKeys(candidate);
      if (keys.some((key) => seen.has(key))) return false;
      for (const key of keys) seen.add(key);
      return true;
    }),
  );
  const merged = [];
  for (let i = 0; merged.length < max && queues.some((queue) => i < queue.length); i += 1) {
    for (const queue of queues) {
      if (i < queue.length && merged.length < max) merged.push(queue[i]);
    }
  }
  return merged;
}

/**
 * Read one source's candidate file for the merge step. A missing file or invalid
 * JSON (a source that died mid-write) is an empty list, never a thrown error, so
 * one dead source cannot fail the run. `status` is 'ok' | 'missing' | 'invalid'.
 */
export function readCandidateFile(path, fs) {
  if (!fs.existsSync(path)) return { candidates: [], status: 'missing' };
  try {
    const parsed = JSON.parse(fs.readFileSync(path, 'utf8'));
    if (Array.isArray(parsed)) return { candidates: parsed, status: 'ok' };
  } catch {
    // fall through to invalid
  }
  return { candidates: [], status: 'invalid' };
}

/** One `source=<name> candidates=<n>[ (missing|invalid)]` line per source. */
export function formatSourceCounts(results) {
  return results.map(({ name, candidates, status }) => `source=${name} candidates=${candidates.length}${status === 'ok' ? '' : ` (${status})`}`);
}

/** A transient API/network failure — the adapters turn this into a warning + an empty candidate list. */
export class SourceApiError extends Error {}
