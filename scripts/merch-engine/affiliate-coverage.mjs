import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUTPUT = 'docs/ops/AFFILIATE-COVERAGE.md';
export const AWIN_DIRECTORY = 'apps/web/lib/longlive/awin-advertisers.json';

const STATUSES = ['wrapped', 'awin-apply', 'pending-signup', 'uncovered', 'direct-by-policy'];

function sourceId(product) {
  return product.source ? `${product.source.eraId}.${product.source.momentId}` : product.category === 'official-store' ? 'official' : 'fanmade';
}

function directStatus(product, awinApplyRetailers) {
  if (product.category === 'official-store') return 'direct-by-policy';
  return awinApplyRetailers.has(product.retailer) ? 'awin-apply' : 'uncovered';
}

function linkFormat(network) {
  if (network === 'awin') return 'awin cread.php + clickref';
  if (network === 'amazon') return 'amazon tag + ascsubtag';
  if (network === 'catchall') return 'catchall redirect + xcust';
  return 'direct retailer URL';
}

function coverageExplanation(status) {
  return status === 'uncovered' ? 'not listed in checked-in E0 Awin advertiser directory' : '';
}

function escapeTableCell(value) {
  return String(value).replace(/\r?\n/g, '<br>').replace(/\|/g, '&#124;');
}

function unescapeTableCell(value) {
  return value.replace(/<br>/g, '\n').replace(/&#124;/g, '|');
}
/** Builds a complete, deterministic coverage report from a catalogue snapshot. */
export function buildCoverage(products, options = {}) {
  const resolveNetwork = options.resolveNetwork ?? (() => ({ network: 'none' }));
  const credentials = options.credentials ?? {};
  const awinApplyRetailers = options.awinApplyRetailers ?? new Set();
  const rows = products
    .map((product) => {
      const resolution = resolveNetwork(product.retailer);
      const network = resolution.network;
      const status =
        network === 'awin' || network === 'amazon' || network === 'catchall'
          ? credentials[network]
            ? 'wrapped'
            : 'pending-signup'
          : directStatus(product, awinApplyRetailers);
      return {
        item: product.item,
        retailer: product.retailer,
        network,
        status,
        linkFormat: linkFormat(network),
        source: sourceId(product),
        reason: coverageExplanation(status),
      };
    })
    .sort((a, b) => a.item.localeCompare(b.item) || a.retailer.localeCompare(b.retailer));
  const summary = Object.fromEntries([
    ['total', rows.length],
    ...STATUSES.map((status) => [status, rows.filter((row) => row.status === status).length]),
  ]);
  return { rows, summary };
}

export function formatCoverage(report) {
  const productRows = report.rows
    .map((row) => `| ${[row.item, row.retailer, row.network, row.status, row.linkFormat, row.source, row.reason].map(escapeTableCell).join(' | ')} |`)
    .join('\n');
  const summaryRows = [
    `| total | ${report.summary.total} |`,
    ...STATUSES.map((status) => `| ${status} | ${report.summary[status]} |`),
  ].join('\n');
  return `<!-- GENERATED by scripts/merch-engine/affiliate-coverage.mjs; DO NOT EDIT. -->\n# Affiliate coverage\n\nThis report is generated from the shipped merchandise catalogue and affiliate resolver. It records only checked-in configuration; it does not assert programme membership or credential state beyond supplied generated artifacts.\n\n## Per-product coverage\n\nThe explanation column is required for every uncovered row. It reports only the checked-in E0 Awin directory state; it does not infer advertiser membership.\n\n| item | retailer | network | status | link-format | source | explanation |\n| --- | --- | --- | --- | --- | --- | --- |\n${productRows}\n\n## Summary\n\n| status | count |\n| --- | ---: |\n${summaryRows}\n`;
}

export function parseCoverage(markdown) {
  const rows = [...markdown.matchAll(/^\| (?!item \||--- \|)(.+?) \| (.+?) \| (.+?) \| (.+?) \| (.+?) \| (.+?) \| (.*?) \|$/gm)].map((match) => ({
    item: unescapeTableCell(match[1]), retailer: unescapeTableCell(match[2]), network: unescapeTableCell(match[3]), status: unescapeTableCell(match[4]), linkFormat: unescapeTableCell(match[5]), source: unescapeTableCell(match[6]), reason: unescapeTableCell(match[7]),
  }));
  const summary = Object.fromEntries([...markdown.matchAll(/^\| (total|wrapped|awin-apply|pending-signup|uncovered|direct-by-policy) \| (\d+) \|$/gm)].map((match) => [match[1], Number(match[2])]));
  return { rows, summary };
}

export function loadAwinApplyRetailers(directoryPath = resolve(ROOT, AWIN_DIRECTORY)) {
  const directory = JSON.parse(readFileSync(directoryPath, 'utf8'));
  return new Set(directory.advertisers.filter(({ joined }) => !joined).map(({ retailer }) => retailer));
}

export function generateCoverage(products, options = {}) {
  return formatCoverage(
    buildCoverage(products, {
      resolveNetwork: options.resolveNetwork,
      credentials: options.credentials,
      awinApplyRetailers: loadAwinApplyRetailers(options.directoryPath),
    }),
  );
}

async function main() {
  const { MERCH_CATALOGUE } = await import('../../apps/web/lib/longlive/merch.ts');
  // The coverage leaf can regenerate while the seam leaf is still awaiting
  // merge. Once present, always use the shipped resolver; the fallback is its
  // fail-closed pre-E0 state (Amazon only, no assumed Awin advertisers).
  let networkFor;
  try {
    ({ networkFor } = await import('../../apps/web/lib/longlive/shop-networks.ts'));
  } catch (error) {
    if (error?.code !== 'ERR_MODULE_NOT_FOUND') throw error;
    networkFor = (retailer) =>
      retailer.trim().toLowerCase().replace(/^www\./, '') === 'amazon.com'
        ? { network: 'amazon' }
        : { network: 'none' };
  }
  // The seam leaf (shop.ts) can regenerate while this leaf is still awaiting
  // merge, same pattern as networkFor above. Once present, always read its
  // boolean-only AFFILIATE_NETWORK_CONFIGURED presence flags; the fallback
  // is the pre-seam fail-closed state (nothing reported configured). This
  // CLI never reads process.env directly (issue #3453, counsel-approved).
  let credentials;
  try {
    ({ AFFILIATE_NETWORK_CONFIGURED: credentials } = await import('../../apps/web/lib/longlive/shop.ts'));
  } catch (error) {
    if (error?.code !== 'ERR_MODULE_NOT_FOUND') throw error;
    credentials = {};
  }
  const products = Object.values(MERCH_CATALOGUE).flat();
  const rendered = generateCoverage(products, {
    resolveNetwork: networkFor,
    credentials,
  });
  writeFileSync(resolve(ROOT, OUTPUT), rendered);
  console.log(`Generated ${OUTPUT} for ${parseCoverage(rendered).summary.total} products.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
