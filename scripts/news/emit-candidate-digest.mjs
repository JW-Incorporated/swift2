#!/usr/bin/env node
/**
 * Emits a sanitized news candidate digest for the News Triage routine.
 *
 * WHY THIS EXISTS
 * ---------------
 * `news_story` is only reachable with SUPABASE_SERVICE_ROLE_KEY, which lives
 * in GitHub Actions secrets. News Triage runs as a cloud agent somewhere else
 * entirely, so it could never read the table — it fired on schedule and filed
 * nothing, every time, while the Vault sat stale at 2026-07-10.
 *
 * The fix is NOT to hand a cloud agent the service_role key. That key bypasses
 * every RLS policy in the project (it already leaked into a committed file
 * once, on 2026-07-19), and a triage routine has no business holding it. So
 * the worker — which legitimately has the key in Actions — publishes a
 * digest of PUBLIC facts (headlines, outlet names, article URLs) into the
 * repo, and triage reads a plain file with zero credentials.
 *
 * SECOND THING THIS BUYS US
 * -------------------------
 * Cross-source clustering in the worker's dedupe step is broken: every story
 * has source_count = 1, so `corroborated` is unreachable and the same event
 * lands N times (Matty Healy's marriage as 4 stories, Shaq as 3). Emitting
 * every story with its outlets in ONE file lets the triage model group them
 * editorially — it can see the four Healy rows — instead of depending on the
 * deterministic dedupe that is failing. Fixing that dedupe still matters for
 * the site's own verification_status; it is no longer a triage blocker.
 *
 * WHAT THIS DOES NOT DO
 * ---------------------
 * No editorial judgment. It does not drop tabloid churn or apply the privacy
 * redlines — that is the triage model's job, working from
 * docs/content-ops/privacy-redlines.md. Filtering here would hide the reason
 * an item was dropped and make a deterministic script the arbiter of an
 * editorial rule. It emits everything and annotates.
 */

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const OUT = 'docs/content-ops/news-candidates.md';
const LOOKBACK_HOURS = 72;
const MAX_STORIES = 120;

function loadEnv() {
  // Actions supplies these directly; locally, fall back to the worker's
  // gitignored .env so a founder can run this by hand.
  if (process.env.SUPABASE_URL && process.env.SUPABASE_SERVICE_ROLE_KEY) return;
  try {
    for (const line of readFileSync('apps/worker/.env', 'utf8').split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/);
      if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
  } catch {
    /* no local .env — fine, we check below */
  }
}

async function main() {
  loadEnv();
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!url || !key) {
    // Same posture as the worker: a missing key is a degraded run, not a
    // crash. Exiting non-zero here would redden the whole news-worker job
    // after the ingest cycle already succeeded.
    console.log('[digest] SUPABASE_URL / SERVICE_ROLE_KEY unset — skipping digest.');
    return;
  }

  const since = new Date(Date.now() - LOOKBACK_HOURS * 3600 * 1000).toISOString();
  const q =
    `${url}/rest/v1/news_story` +
    `?select=id,canonical_title,summary,category,importance,source_count,` +
    `verification_status,first_seen_at,news_story_source(outlet_name,url,tier)` +
    `&first_seen_at=gte.${since}` +
    `&order=first_seen_at.desc&limit=${MAX_STORIES}`;

  const res = await fetch(q, { headers: { apikey: key, Authorization: `Bearer ${key}` } });
  if (!res.ok) {
    console.log(`[digest] query failed: HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    return;
  }
  const stories = await res.json();

  const lines = [];
  lines.push('# News candidates — auto-generated, do not edit by hand');
  lines.push('');
  lines.push(`Emitted by \`scripts/news/emit-candidate-digest.mjs\` from the last ${LOOKBACK_HOURS}h`);
  lines.push('of `news_story`. Regenerated by the `news-worker` workflow after every ingest');
  lines.push('cycle; hand edits are overwritten.');
  lines.push('');
  lines.push('**This is a raw candidate list, NOT a filing queue.** No editorial judgment has');
  lines.push('been applied: tabloid churn, third-party private lives, and privacy-redlined');
  lines.push('material are all still present. News Triage applies the filing bar and');
  lines.push('`docs/content-ops/privacy-redlines.md`; a headline appearing here is not a');
  lines.push('reason to author it.');
  lines.push('');
  lines.push('**Source-URL caveat — read before citing anything.** Items ingested from the');
  lines.push('Google News feeds carry an opaque `news.google.com/rss/articles/CBMi...` redirect');
  lines.push('as their URL, and `outlet_name` is the search feed, not the publisher. Those are');
  lines.push('NOT citable Vault sources. The real publisher is usually visible at the end of');
  lines.push('the summary or title (`... parade.com`, `... - Forbes`). Before filing, resolve');
  lines.push('the actual article URL on the publisher\'s own domain and cite that. If you');
  lines.push('cannot resolve it, the item does not meet the sourcing bar — say so rather than');
  lines.push('filing a redirect link.');
  lines.push('');
  lines.push('**Clustering caveat.** The worker\'s dedupe does not cluster across outlets, so');
  lines.push('`source_count` is 1 almost everywhere and the same event repeats under different');
  lines.push('headlines. Group these yourself before judging corroboration — do not read');
  lines.push('`verification_status: rumor` as "this is a rumor", it mostly means "one outlet');
  lines.push('so far".');
  lines.push('');
  lines.push(`Stories: ${stories.length}`);
  lines.push('');

  if (!stories.length) {
    lines.push('_No stories ingested in the lookback window._');
  }

  for (const s of stories) {
    const seen = (s.first_seen_at || '').slice(0, 16).replace('T', ' ');
    lines.push(`## ${s.canonical_title || '(untitled)'}`);
    lines.push('');
    lines.push(
      `- first seen: ${seen} UTC | category: ${s.category ?? '—'} | importance: ${s.importance ?? '—'}`,
    );
    lines.push(`- verification_status: ${s.verification_status} | source_count: ${s.source_count}`);
    if (s.summary) lines.push(`- summary: ${s.summary.slice(0, 400)}`);
    const srcs = Array.isArray(s.news_story_source) ? s.news_story_source : [];
    if (srcs.length) {
      lines.push('- sources:');
      for (const src of srcs) lines.push(`  - [${src.tier}] ${src.outlet_name} — ${src.url}`);
    } else {
      lines.push('- sources: _none recorded_');
    }
    lines.push('');
  }

  const body = lines.join('\n');
  mkdirSync(dirname(OUT), { recursive: true });

  let prev = null;
  try {
    prev = readFileSync(OUT, 'utf8');
  } catch {
    /* first run */
  }
  if (prev === body) {
    console.log('[digest] unchanged.');
    return;
  }
  writeFileSync(OUT, body);
  console.log(`[digest] wrote ${OUT} (${stories.length} stories).`);
}

main().catch((err) => {
  // Never fail the workflow over the digest — ingest already succeeded.
  console.log(`[digest] unexpected error, skipping: ${err?.message ?? err}`);
});
